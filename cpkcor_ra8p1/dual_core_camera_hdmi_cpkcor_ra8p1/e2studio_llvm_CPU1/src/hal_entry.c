int32_t Disp0_DrawBitmap(int16_t x, int16_t y, int16_t width, int16_t height, const uint8_t *bitmap)
{
	uint32_t err;
	LCD_BitmapType bp;

	bp.x = (uint16_t)x;
	bp.y = (uint16_t)y;
	bp.length = (uint16_t)width;
	bp.width = (uint16_t)height;
	bp.bitmap = bitmap;
	err = LCD_DrawBitmap(&s_lcd_tfp410, 2, &bp);

	return err == FSP_SUCCESS ? 0 : -1;
}

static uint32_t tfp410IicRead(uint8_t *data_w, uint8_t len_w, uint8_t *data_r, uint8_t len_r)
{
	return IIC_WriteRead(0x38, data_w, len_w, data_r, len_r);
}

static uint32_t tfp410IicWrite(uint8_t *data, uint8_t len)
{
	return IIC_Write(0x38, data, len);
}

static void updateCameraToLCD(void)
{
	uint32_t err;

	if (CameraIsCaptureDone(&s_camera_ov5640_mipi) == 0) {
		return;
	}
	if (s_camera_ov5640_mipi.image_ready == NULL) {
		return;
	}
	err = LCD_UpdateLayer1Mem(&s_lcd_tfp410, 2, s_camera_ov5640_mipi.image_ready, true, false);
	if (err) {
		return;
	}
	LCD_Present(&s_lcd_tfp410, 1);
}
