/*******************************************************************************************************************//**
 * main() is generated by the RA Configuration editor and is used to generate threads if an RTOS is used.  This function
 * is called by main() when no RTOS is used.
 **********************************************************************************************************************/
void hal_entry(void)
{
	/* TODO: add your own code here */
	uint32_t err;
	LCD_ConfigType tfp410_cfg;
	CameraConfig ov5640_config_mipi;

	perfc_init(false);
	R_IPC_Open(g_ipc0.p_ctrl, g_ipc0.p_cfg);
	R_IPC_Open(g_ipc1.p_ctrl, g_ipc1.p_cfg);
	IIC_Init();
#if EN_SDRAM_TEST
	puts("Before LCD and camera start, run SDRAM test");
	TestSDRAM(SDRAM_MAP_START_ADDR, SDRAM_SIZE, true, true);
	printf("\r\n\r\n");
#endif

	tfp410_cfg.model = LCD_MODEL_TFP410PAPR;
    tfp410_cfg.peri_1 = &g_lcdc_tfp410;
    tfp410_cfg.peri_model_1 = LCD_PERI_GLCDC;
    tfp410_cfg.peri_2 = NULL;
    tfp410_cfg.peri_model_2 = LCD_PERI_UNUSED;
    tfp410_cfg.iicWrite = tfp410IicWrite;
    tfp410_cfg.iicRead = tfp410IicRead;
    err = LCD_Initialize(&s_lcd_tfp410, &tfp410_cfg);
    REPORT_ERROR(err, 0, "LCD_Initialize() failed: %u", err);
    TestLCD(&s_lcd_tfp410);

    ov5640_config_mipi.model = CAMERA_MODEL_OV5640;
    ov5640_config_mipi.interface = CAMERA_INTERFACE_MIPI_CSI;
    ov5640_config_mipi.length = g_vin_ov5640_cfg_extend.conversion_data.uds_clipping_bits.cl_hsize;
    ov5640_config_mipi.width = g_vin_ov5640_cfg_extend.conversion_data.uds_clipping_bits.cl_vsize;
    ov5640_config_mipi.peripheral_inst = &g_vin_ov5640;
    err = CameraInit(&s_camera_ov5640_mipi, &ov5640_config_mipi);
    REPORT_ERROR(err, 0, "OV5640 MIPI interface init failed: %u", err);
    err = CameraSetFPS(&s_camera_ov5640_mipi, 30, NULL, false);
    REPORT_ERROR(err, 0, "OV5640 MIPI interface set FPS failed: %u", err);
    err = CameraStartCapture(&s_camera_ov5640_mipi, NULL);
    REPORT_ERROR(err, 0, "OV5640 MIPI interface start capture failed: %u", err);

    arm_2d_init();
    disp_adapter0_init();
    CONSOLE_Init();
    arm_2d_scene_player_set_switching_mode(&DISP0_ADAPTER, ARM_2D_SCENE_SWITCH_MODE_FADE_WHITE);
	arm_2d_scene_player_switch_to_next_scene(&DISP0_ADAPTER);

	printf("FSP Version: %s\r\n", FSP_VERSION_STRING);
	puts("CPU0 stdout stream already redirect to CPU1.");
	puts("CPU0 control USER key.");
	puts("You can press key and CPU0 will use printf() to output message.");
	puts("Then CPU1 show it in screen.");

	/* Wake up 2nd core if this is first core and we are inside a multicore project. */
#if (0 == _RA_CORE) && (1 == BSP_MULTICORE_PROJECT) && !BSP_TZ_NONSECURE_BUILD

#if BSP_TZ_SECURE_BUILD
    /* Take semaphore so 2nd core can clear it */
    R_BSP_IpcSemaphoreTake(&g_core_start_semaphore);
#endif

    R_BSP_SecondaryCoreStart();

#if BSP_TZ_SECURE_BUILD
    /* Wait for 2nd core to start and clear semaphore */
    while(FSP_ERR_IN_USE == R_BSP_IpcSemaphoreTake(&g_core_start_semaphore))
    {
        ;
    }
#endif
#endif

#if (1 == _RA_CORE) && (1 == BSP_MULTICORE_PROJECT) && BSP_TZ_SECURE_BUILD
    /* Signal to 1st core that 2nd core has started */
    R_BSP_IpcSemaphoreGive(&g_core_start_semaphore);
#endif

#if EN_ARM2D_BENCHMARK
    arm_2d_run_benchmark(&DISP0_ADAPTER);
#endif

    while (1) {
    	CONSOLE_Task();
    	disp_adapter0_task();
    	updateCameraToLCD();
    }

#if BSP_TZ_SECURE_BUILD
    /* Enter non-secure code */
    R_BSP_NonSecureEnter();
#endif
}

