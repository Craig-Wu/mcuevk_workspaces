#define TFP410_IIC_ADDRESS       0x38

static LCD_DeviceType s_lcd_tfp410;
static LCD_ConfigType s_tfp410_cfg;

static uint32_t tfp410IicRead(uint8_t *data_w, uint8_t len_w, uint8_t *data_r, uint8_t len_r);
static uint32_t tfp410IicWrite(uint8_t *data, uint8_t len);

/*******************************************************************************************************************//**
 * main() is generated by the RA Configuration editor and is used to generate threads if an RTOS is used.  This function
 * is called by main() when no RTOS is used.
 **********************************************************************************************************************/
void hal_entry(void)
{
	/* Initialize the HDMI performance test. */
	perfc_init(false);
#if CONSOLE_CFG_USE_RTT == 0
	SEGGER_RTT_Init();
#endif
	CONSOLE_Init();

	/* Clean screen */
#if CONSOLE_CFG_USE_RTT
    puts(RTT_CTRL_RESET);
    puts(RTT_CTRL_CLEAR);
#else
    puts("\x1b[2J\x1b[H");
    puts("\x1B[0m");
#endif
    printf("FSP Version: %s\r\n", FSP_VERSION_STRING);

    // printf("Before LCD open, SDRAM speed test result\r\n");
    // TestSDRAM(SDRAM_MAP_START_ADDR, SDRAM_SIZE, true, true);
    // printf("\r\n");

    IIC_Init();

    s_tfp410_cfg.model = LCD_MODEL_TFP410PAPR;
    s_tfp410_cfg.peri_1 = &g_lcdc_tfp410;
    s_tfp410_cfg.peri_model_1 = LCD_PERI_GLCDC;
    s_tfp410_cfg.peri_2 = NULL;
    s_tfp410_cfg.peri_model_2 = LCD_PERI_UNUSED;
    s_tfp410_cfg.iicWrite = tfp410IicWrite;
    s_tfp410_cfg.iicRead = tfp410IicRead;
    if (LCD_Initialize(&s_lcd_tfp410, &s_tfp410_cfg) == FSP_SUCCESS) {
        TestLCD(&s_lcd_tfp410);
    }

	/* Wake up 2nd core if this is first core and we are inside a multicore project. */
#if (0 == _RA_CORE) && (1 == BSP_MULTICORE_PROJECT) && !BSP_TZ_NONSECURE_BUILD

#if BSP_TZ_SECURE_BUILD
    /* Take semaphore so 2nd core can clear it */
    R_BSP_IpcSemaphoreTake(&g_core_start_semaphore);
#endif

    R_BSP_SecondaryCoreStart();

#if BSP_TZ_SECURE_BUILD
    /* Wait for 2nd core to start and clear semaphore */
    while(FSP_ERR_IN_USE == R_BSP_IpcSemaphoreTake(&g_core_start_semaphore))
    {
        ;
    }
#endif
#endif

#if (1 == _RA_CORE) && (1 == BSP_MULTICORE_PROJECT) && BSP_TZ_SECURE_BUILD
    /* Signal to 1st core that 2nd core has started */
    R_BSP_IpcSemaphoreGive(&g_core_start_semaphore);
#endif

#if BSP_TZ_SECURE_BUILD
    /* Enter non-secure code */
    R_BSP_NonSecureEnter();
#endif
}

