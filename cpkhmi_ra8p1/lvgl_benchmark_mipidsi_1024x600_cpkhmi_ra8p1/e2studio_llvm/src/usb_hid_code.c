bool HID_CodeIsKeypad(uint8_t code)
{
	if ((code > 0x52) && (code < 0x64)) {
		return true;
	}
	if (code == 0x67) {
		return true;
	}
	if ((code > 0x84) && (code < 0x87)) {
		return true;
	}
	if ((code > 0xAF) && (code < 0xB2)) {
		return true;
	}
	if ((code > 0xB5) && (code < 0xDE)) {
		return true;
	}

	return false;
}
